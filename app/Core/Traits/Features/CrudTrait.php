<?php

namespace App\Core\Traits\Features;

use App\Core\Constants\PermissionConstants;
use App\Core\Services\FeaturesService;
use App\Core\Services\InertiaService;
use App\Core\Services\NotificationService;
use Illuminate\Http\RedirectResponse;
use Inertia\Response;

trait CrudTrait {
    public function list(...$params) : RedirectResponse|Response {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature              = static::feature;
        $permission           = PermissionConstants::permission_list;
        $model_class          = static::get_model_class();
        $render_service_class = static::get_render_service_class();


        //==============================================================================================================
        // Authorization
        //==============================================================================================================



        //==============================================================================================================
        // RenderData
        //==============================================================================================================
        $render_params = $render_service_class::get_render_by_permission($permission, params: $params);

        //==============================================================================================================
        // Register actions
        //==============================================================================================================
        // dd($render_params);
        //==============================================================================================================
        // Render view
        //==============================================================================================================
        return InertiaService::render_feature($feature, $permission, $render_params);
    }



    public function view(...$params) : RedirectResponse|Response {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature              = static::feature;
        $permission           = PermissionConstants::permission_view;
        $model_class          = static::get_model_class();
        $render_service_class = static::get_render_service_class();


        //==============================================================================================================
        // Get model key
        //==============================================================================================================
        $model_key = $params[0];
        $model     = $model_class::get_by_key($model_key);

        if (!$model) {
            return NotificationService::error_to_list($feature, "Model with $model_key not found");
        }


        //==============================================================================================================
        // Authorization
        //==============================================================================================================


        //==============================================================================================================
        // RenderData
        //==============================================================================================================
        $render_params = $render_service_class::get_render_by_permission($permission, $model);


        //==============================================================================================================
        // Register actions
        //==============================================================================================================


        //==============================================================================================================
        // Render view
        //==============================================================================================================
        return InertiaService::render_feature($feature, $permission, $render_params);
    }



    public function create() : RedirectResponse|Response {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature              = static::feature;
        $permission           = PermissionConstants::permission_create;
        $model_class          = static::get_model_class();
        $render_service_class = static::get_render_service_class();


        //==============================================================================================================
        // Authorization



        //==============================================================================================================
        // RenderData
        //==============================================================================================================
        $render_params = $render_service_class::get_render_by_permission($permission);


        //==============================================================================================================
        // Register actions
        //==============================================================================================================


        //==============================================================================================================
        // Render view
        //==============================================================================================================
        return InertiaService::render_feature($feature, $permission, $render_params);
    }



    public function edit(...$params) : RedirectResponse|Response {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature              = static::feature;
        $permission           = PermissionConstants::permission_edit;
        $model_class          = static::get_model_class();
        $render_service_class = static::get_render_service_class();


        //==============================================================================================================
        // Get model key
        //==============================================================================================================
        $model_key = $params[0];
        $model     = $model_class::get_by_key($model_key);

        if (!$model) {
            NotificationService::error("Model with $model_key not found");

            return FeaturesService::redirect_to_list($feature);
        }


        //==============================================================================================================
        // Authorization
        //==============================================================================================================


        //==============================================================================================================
        // RenderData
        //==============================================================================================================
        $render_params = $render_service_class::get_render_by_permission($permission, $model);


        //==============================================================================================================
        // Register actions
        //==============================================================================================================


        //==============================================================================================================
        // Render view
        //==============================================================================================================
        return InertiaService::render_feature($feature, $permission, $render_params);
    }



    public function store() : RedirectResponse {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature            = static::feature;
        $permission         = PermissionConstants::permission_store;
        $model_class        = static::get_model_class();
        $form_request_class = static::get_form_request_class();


        //==============================================================================================================
        // Authorization
        //==============================================================================================================



        //==================================================================================================================
        // Validate attributes
        //==================================================================================================================
        $validated_attributes = app($form_request_class)->validated();


        //==================================================================================================================
        // Create new instance
        //==================================================================================================================
        $model = new $model_class();


        //==================================================================================================================
        // Make dataService filable of modal
        //==================================================================================================================
        $model->fillable(array_keys($validated_attributes));
        $model->fill($validated_attributes);


        //==================================================================================================================
        // Check if model created successfully
        //==================================================================================================================
        if (!$model->save()) {
            NotificationService::error("$feature not saved");
        }


        //==============================================================================================================
        // Register actions
        //==============================================================================================================


        //==============================================================================================================
        // Render view
        //==============================================================================================================
        $label = $model->label();

        NotificationService::success("$label created successfully !");

        $route_name = FeaturesService::get_route_name_by_feature($feature, PermissionConstants::permission_view);

        return to_route($route_name, [$model->key]);
    }



    public function update(...$params) : RedirectResponse {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature            = static::feature;
        $permission         = PermissionConstants::permission_update;
        $model_class        = static::get_model_class();
        $form_request_class = static::get_form_request_class();


        //==============================================================================================================
        // Get model key
        //==============================================================================================================
        $model_key = $params[0];
        $model     = $model_class::get_by_key($model_key);

        if (!$model) {
            NotificationService::error("Model with $model_key not found");

            return FeaturesService::redirect_to_list($feature);
        }


        //==============================================================================================================
        // Authorization
        //==============================================================================================================


        //==================================================================================================================
        // Validate attributes
        //==================================================================================================================
        $validated_attributes = app($form_request_class)->validated();


        //==================================================================================================================
        // Make attributes filable of modal
        //==================================================================================================================
        $model->fillable(array_keys($validated_attributes));


        //==================================================================================================================
        // Check if model updated successfully
        //==================================================================================================================
        if (!$model->update($validated_attributes)) {
            NotificationService::error("$feature Not updated !");
        }


        //==============================================================================================================
        // Register actions
        //==============================================================================================================



        //==============================================================================================================
        // Render view
        //==============================================================================================================
        $label = $model->label();
        NotificationService::success("$label updated successfully !");

        $route_name = FeaturesService::get_route_name_by_feature($feature, PermissionConstants::permission_view);


        return to_route($route_name, [$model->key]);
    }



    public function destroy(...$params) : RedirectResponse {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature     = static::feature;
        $permission  = PermissionConstants::permission_destroy;
        $model_class = static::get_model_class();


        //==============================================================================================================
        // Get model key
        //==============================================================================================================
        $model_key = $params[0];
        $model     = $model_class::get_by_key($model_key);

        if (!$model) {
            NotificationService::error("Model with $model_key not found");

            return FeaturesService::redirect_to_list($feature);
        }


        //==============================================================================================================
        // Authorization
        //==============================================================================================================


        //==================================================================================================================
        // Check if model destroyed successfully
        //==================================================================================================================
        if (!$model->delete()) {
            NotificationService::error("$feature not destroyed !");
        }


        //==============================================================================================================
        // Register actions
        //==============================================================================================================



        $label = $model->label();

        NotificationService::success("$label destroyed successfully !");

        return redirect()->back();
    }



    public function destroy_multi(...$params) : RedirectResponse {
        //==============================================================================================================
        // Get needed classes for every feature
        //==============================================================================================================
        $feature     = static::feature;
        $permission  = PermissionConstants::permission_destroy_multi;
        $model_class = static::get_model_class();


        //==============================================================================================================
        // Authorization
        //==============================================================================================================


        //==================================================================================================================
        // get keys from request
        //==================================================================================================================
        $keys = request('keys');


        //==================================================================================================================
        // delete items by key
        //==================================================================================================================
        $deleted = $model_class::get_by_keys($keys)
                               ->delete();


        if (!$deleted) {
            NotificationService::error("$feature not destroy !");
        }

        NotificationService::success("$feature destroyed successfully !");

        return redirect()->back();
    }
}
